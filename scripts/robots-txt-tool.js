#!/usr/bin/env node
/* eslint-disable no-console */
/**
 * [GGL] robots.txt: download Tilda snapshot → build recommended → sync Worker bodies.
 *
 *   npm run robots:download
 *   npm run robots:build-recommended
 *   npm run robots:sync-worker
 *   npm run robots:verify
 */
const fs = require('fs');
const path = require('path');
const { GOOGLEBOT_PREAMBLE } = require('./lib/robots-txt-preamble');

const ROOT = path.join(__dirname, '..');
const DOCS = path.join(ROOT, 'docs');
const BODIES_OUT = path.join(ROOT, 'cloudflare/alumineu-robots/src/robots-bodies.js');

const SITES = [
  { host: 'alumineu.pl', zone: 'alumineu.pl' },
  { host: 'alumineu.de', zone: 'alumineu.de' },
  { host: 'alumineu.ro', zone: 'alumineu.ro' },
  { host: 'alumineu.com', zone: 'alumineu.com' },
];

function pathsFor(host) {
  return {
    downloaded: path.join(DOCS, `${host}-robots.downloaded.txt`),
    recommended: path.join(DOCS, `${host}-robots.recommended.txt`),
  };
}

function stripCloudflareManaged(text) {
  const begin = text.indexOf('# BEGIN Cloudflare Managed content');
  const end = text.indexOf('# END Cloudflare Managed Content');
  if (begin >= 0 && end > begin) {
    return `${text.slice(0, begin).trim()}\n\n${text.slice(end + '# END Cloudflare Managed Content'.length).trim()}`.trim();
  }
  return text.trim();
}

function stripExistingGooglebot(text) {
  const lines = text.split(/\r?\n/);
  const out = [];
  let i = 0;
  while (i < lines.length) {
    const line = lines[i];
    if (/^User-agent:\s*Googlebot/i.test(line)) {
      i += 1;
      while (i < lines.length && !/^User-agent:/i.test(lines[i]) && !/^User-Agent:/i.test(lines[i])) {
        i += 1;
      }
      continue;
    }
    out.push(line);
    i += 1;
  }
  return out.join('\n').trim();
}

function extractTildaTail(text) {
  let body = stripCloudflareManaged(text);
  body = stripExistingGooglebot(body);
  body = body.replace(/^#.*Merchant Center.*\n/gm, '').trim();
  return body;
}

function buildRecommended(downloadedText) {
  const tail = extractTildaTail(downloadedText);
  return `${GOOGLEBOT_PREAMBLE.trim()}\n\n${tail}\n`.replace(/\n{3,}/g, '\n\n');
}

async function downloadOne(host) {
  const url = `https://${host}/robots.txt`;
  const res = await fetch(url, {
    headers: { 'User-Agent': 'AlumineuRobotsTool/1.0 (+merchant)' },
    redirect: 'follow',
  });
  if (!res.ok) throw new Error(`${url} HTTP ${res.status}`);
  return res.text();
}

async function cmdDownload() {
  for (const { host } of SITES) {
    const { downloaded } = pathsFor(host);
    try {
      const text = await downloadOne(host);
      fs.writeFileSync(downloaded, text.trim() + '\n', 'utf8');
      console.log('[GGL] OK', host, '→', path.relative(ROOT, downloaded), `(${text.split(/\n/).length} lines)`);
    } catch (e) {
      console.warn('[GGL] SKIP', host, '—', e.message);
    }
  }
}

function cmdBuildRecommended() {
  for (const { host } of SITES) {
    const { downloaded, recommended } = pathsFor(host);
    if (!fs.existsSync(downloaded)) {
      console.warn('[GGL] SKIP', host, '— no downloaded file');
      continue;
    }
    const raw = fs.readFileSync(downloaded, 'utf8');
    const out = buildRecommended(raw);
    fs.writeFileSync(recommended, out, 'utf8');
    console.log('[GGL] OK', host, '→', path.relative(ROOT, recommended));
  }
}

function cmdSyncWorker() {
  const entries = [];
  for (const { host } of SITES) {
    const { recommended } = pathsFor(host);
    if (!fs.existsSync(recommended)) {
      console.warn('[GGL] SKIP worker body', host);
      continue;
    }
    const body = fs.readFileSync(recommended, 'utf8').trim();
    entries.push({ host, body });
  }
  if (!entries.length) throw new Error('No recommended robots files — run robots:build-recommended first');

  const lines = [
    '/** [GGL] Auto-generated by npm run robots:sync-worker — do not edit by hand. */',
    '',
    '/** @type {Record<string, string>} */',
    'export const ROBOTS_BY_HOST = {',
  ];
  for (const { host, body } of entries) {
    lines.push(`  '${host}': \`${body.replace(/\\/g, '\\\\').replace(/`/g, '\\`')}\`,`);
    lines.push(`  'www.${host}': \`${body.replace(/\\/g, '\\\\').replace(/`/g, '\\`')}\`,`);
  }
  lines.push('};', '');
  fs.writeFileSync(BODIES_OUT, lines.join('\n'), 'utf8');
  console.log('[GGL] Worker bodies →', path.relative(ROOT, BODIES_OUT), `(${entries.length} zones)`);
}

async function cmdVerify() {
  for (const { host } of SITES) {
    try {
      const text = await downloadOne(host);
      const ok =
        /User-agent:\s*Googlebot/i.test(text) &&
        /Allow:\s*\//i.test(text.split(/User-agent:\s*Googlebot/i)[1] || '');
      console.log(`[GGL] ${ok ? 'OK' : 'FAIL'} ${host}/robots.txt Googlebot Allow`);
      if (!ok) console.log('       First lines:', text.split('\n').slice(0, 8).join(' | '));
    } catch (e) {
      console.warn('[GGL] FAIL', host, '—', e.message);
    }
  }
}

async function main() {
  const cmd = process.argv[2] || 'help';
  if (cmd === 'download') return cmdDownload();
  if (cmd === 'build-recommended') return cmdBuildRecommended();
  if (cmd === 'sync-worker') return cmdSyncWorker();
  if (cmd === 'verify') return cmdVerify();
  if (cmd === 'all') {
    await cmdDownload();
    cmdBuildRecommended();
    cmdSyncWorker();
    return cmdVerify();
  }
  console.log(`Usage:
  node scripts/robots-txt-tool.js download
  node scripts/robots-txt-tool.js build-recommended
  node scripts/robots-txt-tool.js sync-worker
  node scripts/robots-txt-tool.js verify
  node scripts/robots-txt-tool.js all`);
}

main().catch((e) => {
  console.error('[GGL] FAIL:', e.message);
  process.exit(1);
});
